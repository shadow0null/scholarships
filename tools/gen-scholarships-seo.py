#!/usr/bin/env python3
"""Generate SEO files for the scholarships corpus: sitemap.xml, robots.txt,
and JSON-LD structured data injected into each article.

WHAT IT GENERATES (all under articles/, the subdomain web root, so the
writer cron's rebuild-deploy-zip.py picks them up on its next run):
  (a) articles/sitemap.xml — homepage + every real article (275).
      Pilot drafts (pilot-*.html) are EXCLUDED: they are test files, not
      production pages, and the deploy zip excludes them too.
      lastmod = each article's site-data `verified` date (e.g. "16 Oct
      2026"), falling back to the article file's mtime date when no
      verified date is recorded. Both are real dates; a lastmod is never
      invented. Homepage lastmod = articles/index.html mtime date.
  (b) articles/robots.txt — Allow: / for all agents, with a Sitemap
      pointer to https://scholarships.studydesk.fun/sitemap.xml.
  (c) JSON-LD in each article HTML, inserted before </head> as a @graph
      with three nodes (Article, EducationalOccupationalProgram,
      BreadcrumbList):
        - Article: headline, canonical url, datePublished/dateModified
          (verified date, else file mtime), author/publisher StudyDesk,
          about = provider organisation, isBasedOn = the corpus srcUrl
          (the official source page) when the corpus has one.
        - EducationalOccupationalProgram: name, provider, url,
          applicationDeadline (corpus dl) when the corpus has one,
          description (the article's own summary text) when present,
          and offers (price + priceCurrency + the full award text as
          description) ONLY when the corpus award is a clean single
          amount: awardMax is numeric, the award text contains exactly
          one number and one recognisable currency marker. Ranges
          ("Rs 10,000 – 30,000"), prose awards without a number, and
          entries with no award get no offers node — a structured amount
          is never guessed.
      Any field the corpus does not have is skipped, never invented.

IDEMPOTENT: re-running replaces the injected block in place (matched by
its marker comment) and regenerates sitemap/robots; a second run on the
same corpus changes no article file. Existing non-generated ld+json
blocks are never overwritten — they are counted and left alone.

BACKUPS: every article HTML changed is copied first to
  backups/seo-YYYY-MM-DD-HHMMSS/
(sitemap.xml / robots.txt are generated files, not backups of corpus data.)

VALIDATION (runs automatically, printed in the summary):
  * sitemap.xml parses as XML; URL count is reported.
  * robots.txt content is printed.
  * every injected JSON-LD block is re-parsed from disk; a 10-file sample
    is listed by name.

Usage:
  python3 tools/gen-scholarships-seo.py [--dry-run] [--root DIR]
  Test on copies first:
    cp -r ~/workspace/scholarships-17k /tmp/sch-test
    python3 /tmp/sch-test/tools/gen-scholarships-seo.py --root /tmp/sch-test
"""
import argparse
import html as html_lib
import json
import re
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parent))
import scholarship_pills as P  # noqa: E402

MARKER = '<!-- scholarships JSON-LD (generated by tools/gen-scholarships-seo.py) -->'
LD_RE = re.compile(
    re.escape(MARKER) + r'\s*<script type="application/ld\+json">(.*?)</script>',
    re.S)
ANY_LD_RE = re.compile(r'<script type="application/ld\+json">', re.S)

CURRENCIES = [  # order matters: check multi-char markers before bare '$'
    ('A$', 'AUD'), ('C$', 'CAD'), ('US$', 'USD'), ('₹', 'INR'),
    ('Rs', 'INR'), ('€', 'EUR'), ('£', 'GBP'), ('¥', 'JPY'),
    ('CHF', 'CHF'), ('$', 'USD'),
]
NUMBER_RE = re.compile(r'\d[\d,]*\.?\d*')


def plain_text(html_text):
    """Strip tags/entities from article HTML fragments for descriptions."""
    if not html_text:
        return ''
    s = re.sub(r'<[^>]+>', ' ', html_text)
    s = html_lib.unescape(s)
    return re.sub(r'\s+', ' ', s).strip()


def file_date(path):
    """A file's mtime as an Asia/Kolkata date (real, not invented)."""
    ts = path.stat().st_mtime
    return datetime.fromtimestamp(ts, ZoneInfo('Asia/Kolkata')).date()


def lastmod_for(entry, art_path):
    """verified date when recorded, else the article file's mtime date."""
    v = P.parse_dmy(entry.get('verified') or '')
    return v if v else file_date(art_path)


def parse_offers(entry):
    """(price, currency, award_text) or None — only for clean single amounts."""
    award = (entry.get('award') or '').strip()
    amax = entry.get('awardMax')
    if not award or amax is None:
        return None
    if not isinstance(amax, (int, float)):
        return None
    if len(NUMBER_RE.findall(award)) != 1:
        return None  # a range ("10,000 – 30,000") or multi-number prose
    for marker, code in CURRENCIES:
        if marker in award:
            return (amax, code, award)
    return None


def build_json_ld(entry, art_path, base):
    """The @graph dict for one article, or None when nothing can be said."""
    canon = f'{base}/{entry["file"]}'
    pub_date = lastmod_for(entry, art_path).isoformat()
    article = {
        '@type': 'Article',
        'headline': entry.get('title') or '',
        'url': canon,
        'datePublished': pub_date,
        'dateModified': pub_date,
        'author': {'@type': 'Organization', 'name': 'StudyDesk',
                   'url': 'https://studydesk.fun'},
        'publisher': {'@type': 'Organization', 'name': 'StudyDesk',
                      'url': 'https://studydesk.fun'},
    }
    if entry.get('provider'):
        article['about'] = {'@type': 'Organization',
                            'name': entry['provider']}
    if entry.get('srcUrl'):
        article['isBasedOn'] = {'@type': 'WebPage', 'url': entry['srcUrl']}

    prog = {'@type': 'EducationalOccupationalProgram',
            'name': entry.get('title') or '',
            'url': canon}
    if entry.get('provider'):
        prov = {'@type': 'Organization', 'name': entry['provider']}
        if entry.get('srcUrl'):
            prov['url'] = entry['srcUrl']
        prog['provider'] = prov
    if entry.get('dl'):
        prog['applicationDeadline'] = entry['dl']
    desc = plain_text(entry.get('sub') or '')
    if desc:
        prog['description'] = desc
    offers = parse_offers(entry)
    if offers:
        price, code, award_text = offers
        prog['offers'] = {'@type': 'Offer', 'price': price,
                          'priceCurrency': code, 'description': award_text}
    # BreadcrumbList mirrors the visible crumbs (Home / article title).
    # The visible "Scholarships" crumb links to the same "/" as Home, so
    # it is not duplicated as a second item with an identical URL.
    crumbs = {'@type': 'BreadcrumbList',
              'itemListElement': [
                  {'@type': 'ListItem', 'position': 1, 'name': 'Home',
                   'item': f'{base}/'},
                  {'@type': 'ListItem', 'position': 2,
                   'name': entry.get('title') or '', 'item': canon},
              ]}
    return {'@context': 'https://schema.org',
            '@graph': [article, prog, crumbs]}


def render_ld_block(data):
    return (MARKER + '\n<script type="application/ld+json">\n'
            + json.dumps(data, ensure_ascii=False, sort_keys=True, indent=2)
            + '\n</script>')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--root', default=str(P.ROOT),
                    help='corpus root (default: the real corpus)')
    args = ap.parse_args()

    root = Path(args.root)
    art_dir = root / 'articles'
    base = P.BASE_URL
    print(f'gen-scholarships-seo: root={root}'
          + (' DRY-RUN' if args.dry_run else ''))

    entries = json.loads((root / 'site-data.json').read_text(encoding='utf-8'))
    articles = [e for e in entries
                if not P.PILOT_RE.match(e['file'])
                and (art_dir / e['file']).exists()]
    pilots = [e['file'] for e in entries if P.PILOT_RE.match(e['file'])]
    print(f'articles for SEO: {len(articles)} '
          f'(pilots excluded: {pilots})')

    stats = {'sitemap_urls': 0, 'jsonld_injected': 0, 'jsonld_replaced': 0,
             'jsonld_skipped_existing': 0, 'jsonld_no_head': 0,
             'with_offers': 0, 'without_offers': 0, 'with_deadline': 0,
             'with_srcurl': 0, 'files_changed': 0}
    changed_files = {}

    # ---- (a) sitemap.xml ----
    url_entries = []
    index_path = art_dir / 'index.html'
    home_lastmod = file_date(index_path).isoformat() if index_path.exists() else None
    url_entries.append((f'{base}/', home_lastmod))
    for e in sorted(articles, key=lambda x: x['file']):
        lm = lastmod_for(e, art_dir / e['file']).isoformat()
        url_entries.append((f'{base}/{e["file"]}', lm))
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for loc, lm in url_entries:
        lines.append('  <url>')
        lines.append(f'    <loc>{html_lib.escape(loc)}</loc>')
        if lm:
            lines.append(f'    <lastmod>{lm}</lastmod>')
        lines.append('  </url>')
    lines.append('</urlset>')
    sitemap_text = '\n'.join(lines) + '\n'
    stats['sitemap_urls'] = len(url_entries)
    sitemap_path = art_dir / 'sitemap.xml'
    if not args.dry_run:
        sitemap_path.write_text(sitemap_text, encoding='utf-8')
    print(f'sitemap.xml: {len(url_entries)} urls '
          f'(homepage + {len(articles)} articles)')

    # ---- (b) robots.txt ----
    robots_text = ('User-agent: *\n'
                   'Allow: /\n'
                   f'Sitemap: {base}/sitemap.xml\n')
    robots_path = art_dir / 'robots.txt'
    if not args.dry_run:
        robots_path.write_text(robots_text, encoding='utf-8')
    print('robots.txt:')
    print('  ' + robots_text.replace('\n', '\n  ').rstrip())

    # ---- (c) JSON-LD injection ----
    sample = []
    for e in articles:
        fpath = art_dir / e['file']
        html = fpath.read_text(encoding='utf-8')
        data = build_json_ld(e, fpath, base)
        if data['@graph'][1].get('applicationDeadline'):
            stats['with_deadline'] += 1
        if e.get('srcUrl'):
            stats['with_srcurl'] += 1
        if 'offers' in data['@graph'][1]:
            stats['with_offers'] += 1
        else:
            stats['without_offers'] += 1
        block = render_ld_block(data)
        if LD_RE.search(html):
            new_html = LD_RE.sub(lambda _: block, html, count=1)
            action = 'replaced'
        elif ANY_LD_RE.search(html):
            stats['jsonld_skipped_existing'] += 1
            continue
        elif '</head>' not in html:
            stats['jsonld_no_head'] += 1
            continue
        else:
            new_html = html.replace('</head>', block + '\n</head>', 1)
            action = 'injected'
        if new_html != html:
            stats['files_changed'] += 1
            changed_files[str(fpath.relative_to(root))] = fpath.read_bytes()
            if action == 'injected':
                stats['jsonld_injected'] += 1
            else:
                stats['jsonld_replaced'] += 1
            if not args.dry_run:
                fpath.write_text(new_html, encoding='utf-8')
        if len(sample) < 10:
            sample.append(e['file'])

    if changed_files and not args.dry_run:
        stamp = datetime.now(ZoneInfo('Asia/Kolkata')).strftime('%Y-%m-%d-%H%M%S')
        bdir = root / 'backups' / f'seo-{stamp}'
        bdir.mkdir(parents=True, exist_ok=True)
        for rel, blob in changed_files.items():
            dest = bdir / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(blob)
        print(f'backups: {bdir} ({len(changed_files)} files)')

    # ---- validation ----
    print('--- validation ---')
    import xml.etree.ElementTree as ET
    if args.dry_run:
        ET.fromstring(sitemap_text)
        print(f'  sitemap XML parses (dry-run text): '
              f'{len(url_entries)} urls')
    else:
        tree = ET.parse(sitemap_path)
        ns = {'s': 'http://www.sitemaps.org/schemas/sitemap/0.9'}
        urls = tree.getroot().findall('s:url', ns)
        print(f'  sitemap XML parses: {len(urls)} <url> entries on disk')
        assert len(urls) == len(url_entries), 'sitemap count mismatch!'
        robots_on_disk = robots_path.read_text(encoding='utf-8')
        assert robots_on_disk == robots_text, 'robots.txt mismatch!'
        print('  robots.txt on disk matches generated text')
    # every injected block re-parses from disk (or from memory on dry-run)
    bad = 0
    checked = 0
    for e in articles:
        fpath = art_dir / e['file']
        html = fpath.read_text(encoding='utf-8')
        m = LD_RE.search(html)
        if not m:
            continue
        checked += 1
        try:
            parsed = json.loads(m.group(1))
            assert parsed.get('@graph') and len(parsed['@graph']) == 3
        except Exception as exc:  # noqa: BLE001 - report, don't crash
            bad += 1
            print(f'  BAD JSON-LD in {e["file"]}: {exc}')
    print(f'  JSON-LD blocks re-parsed from disk: {checked} ok, {bad} bad')
    print(f'  10-file sample: {sample}')

    print('--- summary ---')
    for k in ('sitemap_urls', 'files_changed', 'jsonld_injected',
              'jsonld_replaced', 'jsonld_skipped_existing', 'jsonld_no_head',
              'with_offers', 'without_offers', 'with_deadline',
              'with_srcurl'):
        print(f'  {k}: {stats[k]}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
